import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const folder = new URL('../src/data/references/', import.meta.url);
const names = readdirSync(folder).filter(name => name.endsWith('.json')).sort();
const ids = new Set();
for (const name of names) {
  const ref = JSON.parse(readFileSync(new URL(name, folder), 'utf8'));
  if (!ref.id || !ref.name || !Array.isArray(ref.nodes) || !Array.isArray(ref.edges)) throw new Error(`Invalid reference: ${name}`);
  if (ids.has(ref.id)) throw new Error(`Duplicate reference ID: ${ref.id}`);
  ids.add(ref.id);
}
const source = '// Generated by scripts/generate-references.mjs. Add reference JSON files to references/.\n'
  + "import type { ReferenceArchitecture } from './referenceTypes.ts';\n"
  + names.map((name, i) => `import reference${i} from ${JSON.stringify(`./references/${name}`)} with { type: 'json' };`).join('\n')
  + '\nexport const REFERENCE_ARCHITECTURES = [' + names.map((_, i) => `reference${i}`).join(', ') + '] as ReferenceArchitecture[];\n';
writeFileSync(new URL('../src/data/referenceRegistry.ts', import.meta.url), source);
